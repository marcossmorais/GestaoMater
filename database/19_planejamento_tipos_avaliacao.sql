-- Mater — Migração 19: planejamento de aula (calendário do diário) e tipos de avaliação
-- Plano: o que o professor pretende dar em uma data; ao registrar a aula, o plano fica ligado a ela.
-- Tipos: o que compõe cada avaliação (prova, trabalho, apresentação…); uma ou mais opções.

CREATE TABLE IF NOT EXISTS plano_aula (
  id_plano integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  fk_id_turma_disciplina integer NOT NULL REFERENCES turma_disciplina (id_turma_disciplina) ON UPDATE CASCADE ON DELETE CASCADE,
  fk_id_professor integer NOT NULL REFERENCES professor (id_professor) ON UPDATE CASCADE,
  fk_id_aula integer REFERENCES aula (id_aula) ON UPDATE CASCADE ON DELETE SET NULL,
  data_aula date NOT NULL,
  titulo varchar(160) NOT NULL,
  quantidade_aulas smallint NOT NULL DEFAULT 1 CHECK (quantidade_aulas BETWEEN 1 AND 10),
  habilidade_bncc_codigo varchar(20),
  habilidade_bncc text,
  objetivos text,
  desenvolvimento text,
  recursos text,
  avaliacao text,
  tarefa text,
  criado_em timestamp(0) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  atualizado_em timestamp(0) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT plano_bncc_codigo_formato CHECK (habilidade_bncc_codigo IS NULL OR habilidade_bncc_codigo ~ '^(EI|EF|EM)[0-9]{2}[A-Z]{2,3}[0-9]{2,3}$')
);

CREATE INDEX IF NOT EXISTS plano_aula_turma_disciplina_data_idx ON plano_aula (fk_id_turma_disciplina, data_aula);
CREATE INDEX IF NOT EXISTS plano_aula_professor_idx ON plano_aula (fk_id_professor);

CREATE TABLE IF NOT EXISTS plano_aula_atividade (
  fk_id_plano integer NOT NULL REFERENCES plano_aula (id_plano) ON UPDATE CASCADE ON DELETE CASCADE,
  tipo varchar(20) NOT NULL CHECK (tipo IN ('teorica', 'documentario', 'questionario', 'revisao', 'pratica', 'avaliacao', 'outro')),
  PRIMARY KEY (fk_id_plano, tipo)
);

CREATE TABLE IF NOT EXISTS avaliacao_tipo (
  fk_id_avaliacao integer NOT NULL REFERENCES avaliacoes (id_avaliacao) ON UPDATE CASCADE ON DELETE CASCADE,
  tipo varchar(20) NOT NULL CHECK (tipo IN ('prova', 'teste', 'atividade', 'tarefa', 'trabalho', 'apresentacao', 'projeto', 'pesquisa', 'redacao', 'pratica', 'participacao', 'outro')),
  PRIMARY KEY (fk_id_avaliacao, tipo)
);

DROP TRIGGER IF EXISTS auditoria_plano_aula ON plano_aula;
CREATE TRIGGER auditoria_plano_aula AFTER INSERT OR UPDATE OR DELETE ON plano_aula
  FOR EACH ROW EXECUTE FUNCTION auditoria_registrar('id_plano');

DROP TRIGGER IF EXISTS auditoria_avaliacao_tipo ON avaliacao_tipo;
CREATE TRIGGER auditoria_avaliacao_tipo AFTER INSERT OR UPDATE OR DELETE ON avaliacao_tipo
  FOR EACH ROW EXECUTE FUNCTION auditoria_registrar('fk_id_avaliacao');
