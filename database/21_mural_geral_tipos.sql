-- Mater — Migração 21: mural com área geral do admin e tipos de aviso
-- aviso_geral: publicado pela coordenação, para toda a escola (fk_id_turma nulo) ou para uma turma; aparece acima dos avisos por matéria.
-- tipo: define a cor e o ícone do aviso nos dois murais.

ALTER TABLE aviso_turma ADD COLUMN IF NOT EXISTS tipo varchar(20) NOT NULL DEFAULT 'aviso'
  CHECK (tipo IN ('aviso', 'prova', 'tarefa', 'material', 'evento', 'urgente'));

CREATE TABLE IF NOT EXISTS aviso_geral (
  id_aviso_geral integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  aviso text NOT NULL,
  tipo varchar(20) NOT NULL DEFAULT 'aviso' CHECK (tipo IN ('aviso', 'prova', 'tarefa', 'material', 'evento', 'urgente')),
  fixado boolean NOT NULL DEFAULT false,
  fk_id_turma integer REFERENCES turma (id_turma) ON UPDATE CASCADE ON DELETE CASCADE,
  fk_id_administrador integer REFERENCES administrador (id_administrador) ON UPDATE CASCADE ON DELETE SET NULL,
  data_postagem timestamp(0) NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS aviso_geral_turma_idx ON aviso_geral (fk_id_turma, data_postagem DESC);

CREATE TABLE IF NOT EXISTS aviso_geral_leitura (
  fk_id_aviso_geral integer NOT NULL REFERENCES aviso_geral (id_aviso_geral) ON UPDATE CASCADE ON DELETE CASCADE,
  fk_id_matricula integer NOT NULL REFERENCES matricula (id_matricula) ON UPDATE CASCADE ON DELETE CASCADE,
  lido_em timestamp(0) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (fk_id_aviso_geral, fk_id_matricula)
);

DROP TRIGGER IF EXISTS auditoria_aviso_geral ON aviso_geral;
CREATE TRIGGER auditoria_aviso_geral AFTER INSERT OR UPDATE OR DELETE ON aviso_geral
  FOR EACH ROW EXECUTE FUNCTION auditoria_registrar('id_aviso_geral');
