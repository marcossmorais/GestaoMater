-- Mater — Migração 12: Diário de aula (habilidade BNCC, atividades e exceções)
-- Proposta v2.0 §03/§04: habilidade BNCC + observação, atividades realizadas na aula,
-- e registro de troca de professor/matéria. Auditado por trigger (ver 10_auditoria.sql).

CREATE TABLE IF NOT EXISTS aula (
  id_aula integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  fk_id_turma_disciplina integer NOT NULL REFERENCES turma_disciplina (id_turma_disciplina) ON UPDATE CASCADE ON DELETE CASCADE,
  fk_id_professor integer NOT NULL REFERENCES professor (id_professor) ON UPDATE CASCADE,
  fk_id_chamada integer REFERENCES chamada (id_chamada) ON UPDATE CASCADE ON DELETE SET NULL,
  data_aula date NOT NULL DEFAULT CURRENT_DATE,
  habilidade_bncc_codigo varchar(20),
  habilidade_bncc text,
  observacao text,
  -- exceções: aula dada por substituto ou matéria trocada no meio da aula
  fk_id_professor_substituto integer REFERENCES professor (id_professor) ON UPDATE CASCADE,
  fk_id_turma_disciplina_ministrada integer REFERENCES turma_disciplina (id_turma_disciplina) ON UPDATE CASCADE,
  motivo_troca varchar(255),
  criado_em timestamp(0) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT aula_bncc_codigo_formato CHECK (habilidade_bncc_codigo IS NULL OR habilidade_bncc_codigo ~ '^(EI|EF|EM)[0-9]{2}[A-Z]{2,3}[0-9]{2,3}$'),
  CONSTRAINT aula_troca_com_motivo CHECK (
    (fk_id_professor_substituto IS NULL AND fk_id_turma_disciplina_ministrada IS NULL) OR motivo_troca IS NOT NULL
  )
);

CREATE INDEX IF NOT EXISTS aula_turma_disciplina_data_idx ON aula (fk_id_turma_disciplina, data_aula DESC);
CREATE INDEX IF NOT EXISTS aula_professor_idx ON aula (fk_id_professor);

CREATE TABLE IF NOT EXISTS aula_atividade (
  fk_id_aula integer NOT NULL REFERENCES aula (id_aula) ON UPDATE CASCADE ON DELETE CASCADE,
  tipo varchar(20) NOT NULL CHECK (tipo IN ('teorica', 'documentario', 'questionario', 'revisao', 'pratica', 'avaliacao', 'outro')),
  PRIMARY KEY (fk_id_aula, tipo)
);

DROP TRIGGER IF EXISTS auditoria_aula ON aula;
CREATE TRIGGER auditoria_aula AFTER INSERT OR UPDATE OR DELETE ON aula
  FOR EACH ROW EXECUTE FUNCTION auditoria_registrar('id_aula');

DROP TRIGGER IF EXISTS auditoria_aula_atividade ON aula_atividade;
CREATE TRIGGER auditoria_aula_atividade AFTER INSERT OR UPDATE OR DELETE ON aula_atividade
  FOR EACH ROW EXECUTE FUNCTION auditoria_registrar('fk_id_aula');
