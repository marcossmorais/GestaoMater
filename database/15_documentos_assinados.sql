-- Mater — Migração 15: Documentos emitidos com assinatura eletrônica verificável (proposta v2.0 §05)
-- Cada declaração/boletim emitido recebe um código público e uma assinatura HMAC-SHA256
-- (chave APP_SIGNING_KEY, fora do banco). Qualquer pessoa confere em /validar?codigo=...
-- Alterar a linha no banco invalida a assinatura.

CREATE TABLE IF NOT EXISTS documento_emitido (
  id_documento integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  codigo varchar(16) NOT NULL UNIQUE,
  tipo varchar(30) NOT NULL CHECK (tipo IN ('declaracao_matricula', 'declaracao_frequencia', 'boletim')),
  fk_id_matricula integer NOT NULL REFERENCES matricula (id_matricula) ON UPDATE CASCADE,
  aluno_nome varchar(150) NOT NULL,
  conteudo_hash char(64) NOT NULL,
  assinatura char(64) NOT NULL,
  emitido_em timestamp(0) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  emitido_por_tipo varchar(20) NOT NULL,
  emitido_por_id integer,
  revogado_em timestamp(0)
);

CREATE INDEX IF NOT EXISTS documento_emitido_matricula_idx ON documento_emitido (fk_id_matricula, tipo, emitido_em DESC);

DROP TRIGGER IF EXISTS auditoria_documento_emitido ON documento_emitido;
CREATE TRIGGER auditoria_documento_emitido AFTER INSERT OR UPDATE OR DELETE ON documento_emitido
  FOR EACH ROW EXECUTE FUNCTION auditoria_registrar('id_documento');
