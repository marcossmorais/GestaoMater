-- Grade de Horários Semanal (Quadro de Aulas)
-- Permite definir os tempos de aula por turno e montar a grade semanal (segunda a sexta) por turma.

CREATE TABLE IF NOT EXISTS horario_aula (
  id_horario_aula integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  fk_id_turno integer NOT NULL REFERENCES turno(id_turno),
  ordem_aula smallint NOT NULL CHECK (ordem_aula BETWEEN 1 AND 8),
  hora_inicio time NOT NULL,
  hora_fim time NOT NULL,
  CONSTRAINT horario_aula_turno_ordem_unique UNIQUE (fk_id_turno, ordem_aula)
);

CREATE TABLE IF NOT EXISTS grade_horario (
  id_grade_horario integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  fk_id_turma integer NOT NULL REFERENCES turma(id_turma) ON UPDATE CASCADE ON DELETE CASCADE,
  fk_id_turma_disciplina integer NOT NULL REFERENCES turma_disciplina(id_turma_disciplina) ON UPDATE CASCADE ON DELETE CASCADE,
  dia_semana smallint NOT NULL CHECK (dia_semana BETWEEN 2 AND 7), -- 2: Segunda, 3: Terça, 4: Quarta, 5: Quinta, 6: Sexta, 7: Sábado
  fk_id_horario_aula integer NOT NULL REFERENCES horario_aula(id_horario_aula),
  CONSTRAINT grade_horario_turma_dia_horario_unique UNIQUE (fk_id_turma, dia_semana, fk_id_horario_aula)
);

CREATE INDEX IF NOT EXISTS grade_horario_turma_idx ON grade_horario (fk_id_turma);
CREATE INDEX IF NOT EXISTS grade_horario_td_idx ON grade_horario (fk_id_turma_disciplina);

