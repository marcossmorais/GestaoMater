-- Povoa automaticamente a grade semanal das turmas existentes com base nas suas disciplinas
DO $$
DECLARE
    r_turma RECORD;
    td_ids integer[];
    h_ids integer[];
    v_td_count integer;
    -- mapeamento de 25 slots na semana (dia 2 a 6, ordem 1 a 5) para índice da disciplina (0 a 11)
    slots integer[] := ARRAY[
        -- Segunda (dia 2, ordens 1..5)
        0, 0, 1, 2, 3,
        -- Terça (dia 3, ordens 1..5)
        1, 1, 4, 5, 6,
        -- Quarta (dia 4, ordens 1..5)
        7, 7, 8, 8, 9,
        -- Quinta (dia 5, ordens 1..5)
        0, 0, 2, 3, 10,
        -- Sexta (dia 6, ordens 1..5)
        1, 4, 5, 6, 11
    ];
    slot_idx integer;
    d_dia integer;
    d_ordem integer;
    curr_td integer;
    curr_h integer;
BEGIN
    FOR r_turma IN SELECT id_turma, fk_id_turno FROM turma LOOP
        -- lista ordenada das disciplinas vinculadas à turma
        SELECT array_agg(id_turma_disciplina ORDER BY id_turma_disciplina)
        INTO td_ids
        FROM turma_disciplina
        WHERE fk_id_turma = r_turma.id_turma;

        v_td_count := array_length(td_ids, 1);
        IF v_td_count IS NULL OR v_td_count = 0 THEN
            CONTINUE;
        END IF;

        -- horários de aula para o turno da turma
        SELECT array_agg(id_horario_aula ORDER BY ordem_aula)
        INTO h_ids
        FROM horario_aula
        WHERE fk_id_turno = r_turma.fk_id_turno;

        IF array_length(h_ids, 1) < 5 THEN
            CONTINUE;
        END IF;

        -- Preenche os 25 tempos da semana
        FOR slot_idx IN 1..25 LOOP
            -- dia: 2 (segunda) até 6 (sexta)
            d_dia := 2 + ((slot_idx - 1) / 5);
            -- ordem: 1 até 5
            d_ordem := 1 + ((slot_idx - 1) % 5);

            curr_h := h_ids[d_ordem];
            curr_td := td_ids[ 1 + (slots[slot_idx] % v_td_count) ];

            INSERT INTO grade_horario (fk_id_turma, fk_id_turma_disciplina, dia_semana, fk_id_horario_aula)
            VALUES (r_turma.id_turma, curr_td, d_dia, curr_h)
            ON CONFLICT (fk_id_turma, dia_semana, fk_id_horario_aula) DO UPDATE
            SET fk_id_turma_disciplina = EXCLUDED.fk_id_turma_disciplina;
        END LOOP;
    END LOOP;
END $$;
