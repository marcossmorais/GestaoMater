-- Mater — Migração 27: substituição do titular do Fund. 1 por período, designada pelo admin.
--
-- Entre data_inicio e data_fim, o substituto (professor já cadastrado) faz a chamada do dia e o diário do dia
-- da turma, só nas datas do período; fora dele, o acesso acaba sozinho. O titular continua com acesso.
-- Afastamento longo: o admin troca o titular da turma (turma.fk_id_professor_titular), não usa esta tabela.
-- Períodos da mesma turma não se sobrepõem (conferido em App/Models/GeneralManagement/Substitution.php).

CREATE TABLE IF NOT EXISTS substituicao_titular (
  id_substituicao integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  fk_id_turma integer NOT NULL REFERENCES turma (id_turma) ON UPDATE CASCADE ON DELETE CASCADE,
  fk_id_professor_substituto integer NOT NULL REFERENCES professor (id_professor) ON UPDATE CASCADE,
  data_inicio date NOT NULL,
  data_fim date NOT NULL,
  motivo varchar(255),
  criado_em timestamp(0) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT substituicao_periodo_valido CHECK (data_fim >= data_inicio)
);

CREATE INDEX IF NOT EXISTS substituicao_substituto_idx ON substituicao_titular (fk_id_professor_substituto, data_fim);
CREATE INDEX IF NOT EXISTS substituicao_turma_idx ON substituicao_titular (fk_id_turma, data_inicio);

-- quem pode lançar falta e diário: trilha de auditoria (database/10_auditoria.sql)
DROP TRIGGER IF EXISTS auditoria_substituicao_titular ON substituicao_titular;
CREATE TRIGGER auditoria_substituicao_titular AFTER INSERT OR UPDATE OR DELETE ON substituicao_titular
  FOR EACH ROW EXECUTE FUNCTION auditoria_registrar('id_substituicao');
