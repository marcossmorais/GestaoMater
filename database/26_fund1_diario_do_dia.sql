-- Mater — Migração 26: diário do dia do Fund. 1 (curso.etapa = 'iniciais').
--
-- O titular registra um texto único por dia para a turma (não um diário por disciplina), com códigos BNCC
-- opcionais de qualquer componente do ano. Uma linha por turma por dia: salvar de novo corrige.
-- Os especialistas continuam no diário por disciplina (tabela aula, migração 12).

CREATE TABLE IF NOT EXISTS diario_dia (
  id_diario_dia integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  fk_id_turma integer NOT NULL REFERENCES turma (id_turma) ON UPDATE CASCADE ON DELETE CASCADE,
  fk_id_professor integer NOT NULL REFERENCES professor (id_professor) ON UPDATE CASCADE,
  data_aula date NOT NULL,
  texto text NOT NULL,
  habilidades_bncc varchar(20)[] NOT NULL DEFAULT '{}',
  criado_em timestamp(0) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  atualizado_em timestamp(0) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT diario_dia_turma_data_key UNIQUE (fk_id_turma, data_aula),
  CONSTRAINT diario_dia_texto_tamanho CHECK (char_length(btrim(texto)) BETWEEN 1 AND 4000),
  CONSTRAINT diario_dia_bncc_formato CHECK (
    array_to_string(habilidades_bncc, ',') ~ '^((EI|EF|EM)[0-9]{2}[A-Z]{2,3}[0-9]{2,3}(,|$))*$'
  )
);

-- registro pedagógico do docente: trilha de auditoria (database/10_auditoria.sql)
DROP TRIGGER IF EXISTS auditoria_diario_dia ON diario_dia;
CREATE TRIGGER auditoria_diario_dia AFTER INSERT OR UPDATE OR DELETE ON diario_dia
  FOR EACH ROW EXECUTE FUNCTION auditoria_registrar('id_diario_dia');
