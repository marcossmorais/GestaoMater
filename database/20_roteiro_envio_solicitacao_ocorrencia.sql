-- Mater — Migração 20: envio do roteiro de provas à coordenação e solicitação de ocorrência pelo professor
-- Roteiro: ao salvar, o professor envia; o admin recebe e marca como visto. Editar de novo volta a ficar "não visto".
-- Solicitação: o professor pede, o admin aceita (vira ocorrência) ou recusa. Observação rápida não muda.

ALTER TABLE avaliacoes ADD COLUMN IF NOT EXISTS roteiro_enviado_em timestamp(0);
ALTER TABLE avaliacoes ADD COLUMN IF NOT EXISTS roteiro_visto_em timestamp(0);
ALTER TABLE avaliacoes ADD COLUMN IF NOT EXISTS roteiro_enviado_por integer REFERENCES professor (id_professor) ON UPDATE CASCADE ON DELETE SET NULL;

CREATE INDEX IF NOT EXISTS avaliacoes_roteiro_enviado_idx ON avaliacoes (roteiro_enviado_em DESC) WHERE roteiro_enviado_em IS NOT NULL;

CREATE TABLE IF NOT EXISTS solicitacao_ocorrencia (
  id_solicitacao integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  fk_id_matricula integer NOT NULL REFERENCES matricula (id_matricula) ON UPDATE CASCADE ON DELETE CASCADE,
  fk_id_turma_disciplina integer NOT NULL REFERENCES turma_disciplina (id_turma_disciplina) ON UPDATE CASCADE ON DELETE CASCADE,
  fk_id_professor integer NOT NULL REFERENCES professor (id_professor) ON UPDATE CASCADE,
  categoria varchar(30) NOT NULL CHECK (categoria IN ('Elogio', 'Disciplinar', 'Pedagógica')),
  titulo varchar(150) NOT NULL,
  descricao text NOT NULL,
  gravidade varchar(20) NOT NULL DEFAULT 'Média' CHECK (gravidade IN ('Baixa', 'Média', 'Alta', 'Gravíssima')),
  data_fato date NOT NULL,
  situacao varchar(20) NOT NULL DEFAULT 'pendente' CHECK (situacao IN ('pendente', 'aceita', 'recusada')),
  resposta varchar(255),
  fk_id_ocorrencia integer REFERENCES ocorrencia_disciplinar (id_ocorrencia) ON UPDATE CASCADE ON DELETE SET NULL,
  analisada_em timestamp(0),
  criado_em timestamp(0) NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS solicitacao_ocorrencia_situacao_idx ON solicitacao_ocorrencia (situacao, criado_em DESC);
CREATE INDEX IF NOT EXISTS solicitacao_ocorrencia_matricula_idx ON solicitacao_ocorrencia (fk_id_matricula, criado_em DESC);

DROP TRIGGER IF EXISTS auditoria_solicitacao_ocorrencia ON solicitacao_ocorrencia;
CREATE TRIGGER auditoria_solicitacao_ocorrencia AFTER INSERT OR UPDATE OR DELETE ON solicitacao_ocorrencia
  FOR EACH ROW EXECUTE FUNCTION auditoria_registrar('id_solicitacao');
