-- Regra de aprovação usada pelo simulador. Uma linha só.
-- VALORES PADRÃO A CONFIRMAR COM A DIREÇÃO DO MATER (média, unidades e frequência mínima).
CREATE TABLE IF NOT EXISTS regra_aprovacao (
  id_regra_aprovacao integer PRIMARY KEY DEFAULT 1 CHECK (id_regra_aprovacao = 1),
  total_unidades smallint NOT NULL DEFAULT 3 CHECK (total_unidades BETWEEN 1 AND 6),
  pontos_por_unidade numeric(4,1) NOT NULL DEFAULT 10 CHECK (pontos_por_unidade > 0),
  media_aprovacao numeric(4,1) NOT NULL DEFAULT 6 CHECK (media_aprovacao > 0),
  frequencia_minima smallint NOT NULL DEFAULT 75 CHECK (frequencia_minima BETWEEN 0 AND 100),
  atualizado_em timestamp(0) NOT NULL DEFAULT CURRENT_TIMESTAMP
);

INSERT INTO regra_aprovacao (id_regra_aprovacao) VALUES (1) ON CONFLICT DO NOTHING;

-- Cronograma: eventos da escola (fk_id_turma nulo) ou de uma turma. Cadastro pelo Admin.
CREATE TABLE IF NOT EXISTS evento_escolar (
  id_evento integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  titulo varchar(120) NOT NULL,
  descricao text,
  tipo varchar(20) NOT NULL DEFAULT 'evento' CHECK (tipo IN ('evento', 'feriado', 'prova', 'reuniao', 'recesso', 'outro')),
  data_inicio date NOT NULL,
  data_fim date,
  fk_id_turma integer REFERENCES turma (id_turma) ON UPDATE CASCADE ON DELETE CASCADE,
  criado_em timestamp(0) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT evento_periodo_valido CHECK (data_fim IS NULL OR data_fim >= data_inicio)
);

CREATE INDEX IF NOT EXISTS evento_escolar_data_idx ON evento_escolar (data_inicio);
CREATE INDEX IF NOT EXISTS evento_escolar_turma_idx ON evento_escolar (fk_id_turma);

DROP TRIGGER IF EXISTS auditoria_evento_escolar ON evento_escolar;
CREATE TRIGGER auditoria_evento_escolar AFTER INSERT OR UPDATE OR DELETE ON evento_escolar
  FOR EACH ROW EXECUTE FUNCTION auditoria_registrar('id_evento');

DROP TRIGGER IF EXISTS auditoria_regra_aprovacao ON regra_aprovacao;
CREATE TRIGGER auditoria_regra_aprovacao AFTER INSERT OR UPDATE OR DELETE ON regra_aprovacao
  FOR EACH ROW EXECUTE FUNCTION auditoria_registrar('id_regra_aprovacao');
