-- Mater — Migração 24: Fund. 1 (curso.etapa = 'iniciais') com professor titular e chamada diária.
--
-- turma.fk_id_professor_titular: o polivalente da turma, marcado pelo admin. Ele faz a chamada do dia.
-- As disciplinas continuam em turma_disciplina: as do titular com ele, as dos especialistas com cada um;
-- cada professor edita só as disciplinas atribuídas a ele (App/Models/Teacher/TeacherAccess.php).
--
-- chamada_diaria: uma por turma por dia, feita pelo titular; a frequência do Fund. 1 é contada em dias
-- (dias letivos = dias com chamada). Salvar de novo no mesmo dia corrige a lista (não soma).
-- Dia de falta coberto por atestado aprovado conta como abonado (calculado, não gravado).

ALTER TABLE turma ADD COLUMN IF NOT EXISTS fk_id_professor_titular integer
  REFERENCES professor (id_professor) ON UPDATE CASCADE ON DELETE SET NULL;

CREATE TABLE IF NOT EXISTS chamada_diaria (
  id_chamada_diaria integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  fk_id_turma integer NOT NULL REFERENCES turma (id_turma) ON UPDATE CASCADE ON DELETE CASCADE,
  fk_id_unidade integer NOT NULL REFERENCES unidade (id_unidade),
  fk_id_professor integer NOT NULL REFERENCES professor (id_professor) ON UPDATE CASCADE,
  data_aula date NOT NULL,
  total_presentes integer NOT NULL DEFAULT 0,
  total_ausentes integer NOT NULL DEFAULT 0,
  matriculas_ausentes integer[] NOT NULL DEFAULT '{}',
  criado_em timestamp(0) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  atualizado_em timestamp(0) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT chamada_diaria_turma_data_key UNIQUE (fk_id_turma, data_aula)
);

CREATE INDEX IF NOT EXISTS chamada_diaria_unidade_idx ON chamada_diaria (fk_id_turma, fk_id_unidade);
CREATE INDEX IF NOT EXISTS chamada_diaria_ausentes_idx ON chamada_diaria USING gin (matriculas_ausentes);

-- falta é dado sensível: trilha de auditoria (database/10_auditoria.sql)
DROP TRIGGER IF EXISTS auditoria_chamada_diaria ON chamada_diaria;
CREATE TRIGGER auditoria_chamada_diaria AFTER INSERT OR UPDATE OR DELETE ON chamada_diaria
  FOR EACH ROW EXECUTE FUNCTION auditoria_registrar('id_chamada_diaria');

DROP TRIGGER IF EXISTS auditoria_turma_titular ON turma;
CREATE TRIGGER auditoria_turma_titular AFTER UPDATE OF fk_id_professor_titular ON turma
  FOR EACH ROW EXECUTE FUNCTION auditoria_registrar('id_turma');
