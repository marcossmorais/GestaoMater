-- Chamada rápida (portal do docente)
-- Cada registro é uma chamada feita pelo professor em uma turma/disciplina.
-- As faltas continuam somadas em falta_aluno (total por unidade); esta tabela guarda o histórico
-- e permite avisar quando a chamada do dia já foi feita.

CREATE TABLE IF NOT EXISTS chamada (
  id_chamada integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  fk_id_turma_disciplina integer NOT NULL REFERENCES turma_disciplina (id_turma_disciplina) ON UPDATE CASCADE ON DELETE CASCADE,
  fk_id_unidade integer NOT NULL REFERENCES unidade (id_unidade),
  fk_id_professor integer NOT NULL REFERENCES professor (id_professor) ON UPDATE CASCADE ON DELETE CASCADE,
  data_aula date NOT NULL DEFAULT CURRENT_DATE,
  quantidade_aulas smallint NOT NULL DEFAULT 1 CHECK (quantidade_aulas BETWEEN 1 AND 6),
  total_presentes integer NOT NULL DEFAULT 0,
  total_ausentes integer NOT NULL DEFAULT 0,
  matriculas_ausentes integer[] NOT NULL DEFAULT '{}',
  criado_em timestamp(0) NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS chamada_turma_disciplina_data_idx ON chamada (fk_id_turma_disciplina, data_aula);
CREATE INDEX IF NOT EXISTS chamada_professor_idx ON chamada (fk_id_professor);

-- Busca de faltas por aluno/disciplina/unidade (usada a cada chamada salva)
CREATE INDEX IF NOT EXISTS falta_aluno_matricula_disciplina_unidade_idx
  ON falta_aluno (fk_id_matricula_falta, fk_id_turma_disciplina_falta, fk_id_unidade_falta);
